import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:share_plus/share_plus.dart';

enum FlashcardExportFormat {
  ankiTsv,
  quizlet,
  markdown,
}

/// Formats and exports flashcard decks for Anki, Quizlet, and printable study guides.
class FlashcardExportService {
  /// Converts cards to Anki-compatible TSV format (Tab-Separated Values).
  ///
  /// Columns: Front \t Back \t Tags
  /// Newlines within card text are converted to HTML `<br>` as expected by Anki.
  static String toAnkiTsv(List<Map<String, String>> cards, {String? deckName}) {
    final buffer = StringBuffer();
    final tag = (deckName ?? 'StudyVault').replaceAll(RegExp(r'\s+'), '_');

    for (final card in cards) {
      final rawFront = card['front'] ?? '';
      final rawBack = card['back'] ?? '';

      final cleanFront = rawFront
          .replaceAll('\t', ' ')
          .replaceAll('\r\n', '<br>')
          .replaceAll('\n', '<br>')
          .trim();

      final cleanBack = rawBack
          .replaceAll('\t', ' ')
          .replaceAll('\r\n', '<br>')
          .replaceAll('\n', '<br>')
          .trim();

      buffer.writeln('$cleanFront\t$cleanBack\t$tag');
    }

    return buffer.toString();
  }

  /// Converts cards to Quizlet import format.
  ///
  /// Separates term and definition with Tab `\t` and cards with newline `\n`.
  static String toQuizlet(List<Map<String, String>> cards) {
    final buffer = StringBuffer();

    for (final card in cards) {
      final front = (card['front'] ?? '').replaceAll('\t', ' ').replaceAll('\n', ' ').trim();
      final back = (card['back'] ?? '').replaceAll('\t', ' ').replaceAll('\n', ' ').trim();
      buffer.writeln('$front\t$back');
    }

    return buffer.toString();
  }

  /// Formats cards into a clean, printable Markdown study sheet / cheatsheet.
  static String toStudyGuideMarkdown(List<Map<String, String>> cards, {required String topic}) {
    final buffer = StringBuffer();
    buffer.writeln('# 📚 Study Guide & Flashcard Deck: $topic');
    buffer.writeln('*Generated by StudyVault on ${DateTime.now().toLocal().toString().split(' ')[0]}*');
    buffer.writeln('\n---\n');

    buffer.writeln('| # | Question / Concept | Answer / Definition |');
    buffer.writeln('|:---:|:---|:---|');

    for (var i = 0; i < cards.length; i++) {
      final card = cards[i];
      final front = (card['front'] ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ').trim();
      final back = (card['back'] ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ').trim();
      buffer.writeln('| ${i + 1} | $front | $back |');
    }

    buffer.writeln('\n---\n');
    buffer.writeln('### Flashcard Cards Listing (Double-Sided Study)\n');

    for (var i = 0; i < cards.length; i++) {
      final card = cards[i];
      buffer.writeln('#### Card ${i + 1}');
      buffer.writeln('**Q:** ${card['front']?.trim() ?? ''}\n');
      buffer.writeln('**A:** ${card['back']?.trim() ?? ''}\n');
      buffer.writeln('---');
    }

    return buffer.toString();
  }

  /// Displays the interactive Export modal bottom sheet.
  static Future<void> showExportDialog(
    BuildContext context, {
    required String topic,
    required List<Map<String, String>> cards,
  }) {
    return showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (ctx) => _FlashcardExportModal(topic: topic, cards: cards),
    );
  }
}

class _FlashcardExportModal extends StatefulWidget {
  final String topic;
  final List<Map<String, String>> cards;

  const _FlashcardExportModal({required this.topic, required this.cards});

  @override
  State<_FlashcardExportModal> createState() => _FlashcardExportModalState();
}

class _FlashcardExportModalState extends State<_FlashcardExportModal> {
  FlashcardExportFormat _selectedFormat = FlashcardExportFormat.ankiTsv;

  String _getFormattedContent() {
    switch (_selectedFormat) {
      case FlashcardExportFormat.ankiTsv:
        return FlashcardExportService.toAnkiTsv(widget.cards, deckName: widget.topic);
      case FlashcardExportFormat.quizlet:
        return FlashcardExportService.toQuizlet(widget.cards);
      case FlashcardExportFormat.markdown:
        return FlashcardExportService.toStudyGuideMarkdown(widget.cards, topic: widget.topic);
    }
  }

  void _copyToClipboard() {
    final content = _getFormattedContent();
    Clipboard.setData(ClipboardData(text: content));
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text('Copied ${_selectedFormat.name} data to clipboard!'),
        behavior: SnackBarBehavior.floating,
        duration: const Duration(seconds: 2),
      ),
    );
  }

  void _shareContent() {
    final content = _getFormattedContent();
    SharePlus.instance.share(
      ShareParams(
        text: content,
        subject: 'StudyVault Flashcards: ${widget.topic}',
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;
    final content = _getFormattedContent();

    return Container(
      height: MediaQuery.of(context).size.height * 0.75,
      padding: const EdgeInsets.fromLTRB(20, 16, 20, 24),
      decoration: BoxDecoration(
        color: isDark ? const Color(0xFF1E1E24) : Colors.white,
        borderRadius: const BorderRadius.vertical(top: Radius.circular(24)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          // Header
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Text(
                'Export Flashcard Deck',
                style: theme.textTheme.titleMedium?.copyWith(fontWeight: FontWeight.bold),
              ),
              IconButton(
                icon: const Icon(Icons.close_rounded),
                onPressed: () => Navigator.pop(context),
              ),
            ],
          ),
          const SizedBox(height: 12),

          // Format Segmented Control
          SegmentedButton<FlashcardExportFormat>(
            segments: const [
              ButtonSegment(
                value: FlashcardExportFormat.ankiTsv,
                label: Text('Anki (TSV)'),
                icon: Icon(Icons.file_download_outlined, size: 16),
              ),
              ButtonSegment(
                value: FlashcardExportFormat.quizlet,
                label: Text('Quizlet'),
                icon: Icon(Icons.quiz_outlined, size: 16),
              ),
              ButtonSegment(
                value: FlashcardExportFormat.markdown,
                label: Text('Markdown / PDF'),
                icon: Icon(Icons.description_outlined, size: 16),
              ),
            ],
            selected: {_selectedFormat},
            onSelectionChanged: (val) {
              setState(() => _selectedFormat = val.first);
            },
          ),

          const SizedBox(height: 16),

          // Content Preview
          Expanded(
            child: Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: isDark ? const Color(0xFF121216) : const Color(0xFFF3F4F6),
                borderRadius: BorderRadius.circular(12),
                border: Border.all(color: isDark ? Colors.white10 : Colors.black12),
              ),
              child: SingleChildScrollView(
                child: SelectableText(
                  content,
                  style: const TextStyle(
                    fontFamily: 'monospace',
                    fontSize: 12,
                    height: 1.4,
                  ),
                ),
              ),
            ),
          ),

          const SizedBox(height: 16),

          // Actions
          Row(
            children: [
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: _shareContent,
                  icon: const Icon(Icons.share_rounded),
                  label: const Text('Share / Save'),
                  style: OutlinedButton.styleFrom(
                    padding: const EdgeInsets.symmetric(vertical: 14),
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                  ),
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: ElevatedButton.icon(
                  onPressed: _copyToClipboard,
                  icon: const Icon(Icons.copy_rounded),
                  label: const Text('Copy to Clipboard'),
                  style: ElevatedButton.styleFrom(
                    padding: const EdgeInsets.symmetric(vertical: 14),
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                  ),
                ),
              ),
            ],
          ),
        ],
      ),
    );
  }
}
